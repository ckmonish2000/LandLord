#!/usr/bin/env python3
"""Pack a project directory into a single self-extracting Python script.

Files matched by the project's .gitignore files (including nested ones) are
left out. Running the generated script recreates the project.

Usage:
    python pack_project.py <project_dir> [-o bundle.py] [--exclude PATTERN ...] [--dry-run]

Then, anywhere with Python 3.8+:
    python bundle.py [dest_dir] [--force] [--list]
"""

from __future__ import annotations

import argparse
import base64
import io
import os
import re
import sys
import tarfile
import textwrap
from dataclasses import dataclass
from pathlib import Path

# Always skipped, whatever .gitignore says.
ALWAYS_EXCLUDE = [".git/"]

# Restore logic shared by the generated bundle and unpack_project.py.
# It is stored as source text so it can be embedded verbatim in each bundle.
RUNTIME = r'''
import base64, io, os, sys, tarfile
from pathlib import Path, PurePosixPath


def load_archive(payload):
    data = base64.b64decode("".join(payload.split()))
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:xz")


def _check_member(member, dest):
    path = PurePosixPath(member.name)
    if path.is_absolute() or ".." in path.parts:
        raise ValueError(f"unsafe path in archive: {member.name}")
    if member.issym() or member.islnk():
        target = PurePosixPath(member.linkname)
        base = path.parent if member.issym() else PurePosixPath()
        resolved = os.path.normpath(str(base / target))
        if target.is_absolute() or resolved.startswith(".."):
            raise ValueError(f"unsafe link in archive: {member.name} -> {member.linkname}")
    elif not (member.isfile() or member.isdir()):
        raise ValueError(f"unsupported entry in archive: {member.name}")


def extract(payload, dest, force=False):
    dest = Path(dest).resolve()
    if dest.exists() and any(dest.iterdir()) and not force:
        sys.exit(f"error: {dest} exists and is not empty (use --force to overwrite)")
    with load_archive(payload) as tar:
        members = tar.getmembers()
        for member in members:
            _check_member(member, dest)
        dest.mkdir(parents=True, exist_ok=True)
        for member in members:
            target = dest / member.name
            if force and (target.is_symlink() or target.is_file()):
                target.unlink()
            tar.extract(member, dest, set_attrs=True)
    print(f"Restored {sum(m.isfile() for m in members)} files to {dest}")


def list_files(payload):
    with load_archive(payload) as tar:
        for member in tar.getmembers():
            if not member.isdir():
                print(f"{member.size:>10}  {member.name}")
'''

BUNDLE_TEMPLATE = '''#!/usr/bin/env python3
"""Self-extracting bundle of the "{name}" project ({count} files).

Generated by pack_project.py. Usage:
    python {script} [dest_dir] [--force] [--list]

dest_dir defaults to ./{name}
"""
import argparse
{runtime}

PROJECT_NAME = {name!r}
PAYLOAD = """
{payload}
"""


def main():
    parser = argparse.ArgumentParser(description="Recreate the {name} project.")
    parser.add_argument("dest", nargs="?", default=PROJECT_NAME, help="output directory")
    parser.add_argument("--force", action="store_true", help="overwrite a non-empty directory")
    parser.add_argument("--list", action="store_true", help="list files without extracting")
    args = parser.parse_args()
    if args.list:
        list_files(PAYLOAD)
    else:
        extract(PAYLOAD, args.dest, force=args.force)


if __name__ == "__main__":
    main()
'''


# --------------------------------------------------------------------------- #
# .gitignore matching
# --------------------------------------------------------------------------- #


@dataclass
class Rule:
    base: str  # directory holding the .gitignore, relative to the project root ("" = root)
    regex: re.Pattern[str]
    negate: bool
    dir_only: bool


def _glob_to_regex(pattern: str) -> str:
    out, i, n = [], 0, len(pattern)
    while i < n:
        c = pattern[i]
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("/**", i) and i + 3 == n:
            out.append("/.*")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif c == "*":
            out.append("[^/]*")
            i += 1
        elif c == "?":
            out.append("[^/]")
            i += 1
        elif c == "[":
            end = pattern.find("]", i + 2)
            if end == -1:
                out.append(re.escape(c))
                i += 1
            else:
                body = pattern[i + 1 : end]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append(f"[{body}]")
                i = end + 1
        elif c == "\\" and i + 1 < n:
            out.append(re.escape(pattern[i + 1]))
            i += 2
        else:
            out.append(re.escape(c))
            i += 1
    return "".join(out)


def parse_rule(line: str, base: str) -> Rule | None:
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"):
        return None
    if not line.endswith("\\ "):
        line = line.rstrip()
    negate = line.startswith("!")
    if negate or line.startswith("\\!") or line.startswith("\\#"):
        line = line[1:]
    dir_only = line.endswith("/")
    line = line.rstrip("/")
    if not line:
        return None
    anchored = "/" in line
    line = line.lstrip("/")
    body = _glob_to_regex(line)
    regex = re.compile(("" if anchored else "(?:.*/)?") + body + "$")
    return Rule(base, regex, negate, dir_only)


def read_rules(directory: Path, base: str) -> list[Rule]:
    gitignore = directory / ".gitignore"
    if not gitignore.is_file():
        return []
    text = gitignore.read_text(encoding="utf-8", errors="replace")
    return [r for line in text.splitlines() if (r := parse_rule(line, base))]


def is_ignored(rel_path: str, is_dir: bool, rules: list[Rule]) -> bool:
    ignored = False
    for rule in rules:  # later rules (and deeper .gitignore files) win
        if rule.dir_only and not is_dir:
            continue
        if rule.base:
            if not rel_path.startswith(rule.base + "/"):
                continue
            candidate = rel_path[len(rule.base) + 1 :]
        else:
            candidate = rel_path
        if rule.regex.match(candidate):
            ignored = not rule.negate
    return ignored


def collect_files(root: Path, extra_excludes: list[str], skip: set[Path]) -> list[Path]:
    """Walk the project, honouring nested .gitignore files. Ignored dirs are not entered."""
    base_rules = [r for p in ALWAYS_EXCLUDE + extra_excludes if (r := parse_rule(p, ""))]
    files: list[Path] = []

    def walk(directory: Path, rules: list[Rule]) -> None:
        rel_dir = directory.relative_to(root).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir
        rules = rules + read_rules(directory, rel_dir)
        for entry in sorted(directory.iterdir(), key=lambda p: p.name):
            rel = entry.relative_to(root).as_posix()
            is_dir = entry.is_dir() and not entry.is_symlink()
            if entry.resolve() in skip or is_ignored(rel, is_dir, rules):
                continue
            if is_dir:
                walk(entry, rules)
            elif entry.is_file() or entry.is_symlink():
                files.append(entry)

    walk(root, base_rules)
    return files


# --------------------------------------------------------------------------- #
# Packing
# --------------------------------------------------------------------------- #


def build_payload(root: Path, files: list[Path]) -> str:
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:xz", preset=9) as tar:
        for path in files:
            info = tar.gettarinfo(str(path), arcname=path.relative_to(root).as_posix())
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            if info.isfile():
                with path.open("rb") as fh:
                    tar.addfile(info, fh)
            else:
                tar.addfile(info)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    return "\n".join(textwrap.wrap(encoded, 100))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("project_dir", type=Path, help="directory to pack")
    parser.add_argument("-o", "--output", type=Path, help="output script (default: <name>_bundle.py)")
    parser.add_argument("--exclude", action="append", default=[], metavar="PATTERN",
                        help="extra gitignore-style pattern to skip (repeatable)")
    parser.add_argument("--dry-run", action="store_true", help="list files that would be packed")
    args = parser.parse_args()

    root = args.project_dir.resolve()
    if not root.is_dir():
        sys.exit(f"error: {root} is not a directory")
    name = root.name
    output = (args.output or Path(f"{name}_bundle.py")).resolve()

    files = collect_files(root, args.exclude, skip={output})
    if args.dry_run:
        for path in files:
            print(path.relative_to(root).as_posix())
        print(f"\n{len(files)} files")
        return

    raw_size = sum(p.stat().st_size for p in files if p.is_file() and not p.is_symlink())
    script = BUNDLE_TEMPLATE.format(
        name=name,
        count=len(files),
        script=output.name,
        runtime=RUNTIME.strip(),
        payload=build_payload(root, files),
    )
    output.write_text(script, encoding="utf-8")
    output.chmod(0o755)
    print(f"Packed {len(files)} files ({raw_size / 1024:.0f} KB) into {output} "
          f"({output.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
